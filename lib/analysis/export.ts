import type { AnalysisResult } from '@/lib/types';
import { languageContext, LANGUAGE_LIMITATION } from './language-context';

export function formatLyricsExport(analysis: AnalysisResult): string {
  return [
      `Song Lyric Analysis`,
      `───────────────────`,
      `Mood:      ${analysis.mood}`,
      `Vibe:      ${analysis.vibe}`,
      `Energy:    ${analysis.energy}`,
      `Sentiment: ${analysis.sentiment}`,
      `Themes:    ${analysis.themes.join(', ')}`,
      `Heuristic confidence: ${Math.round(analysis.confidence * 100)}%`,
      languageContext(analysis.languageProcessing).title,
      languageContext(analysis.languageProcessing).detail,
      LANGUAGE_LIMITATION,
      ``,
      analysis.detailedAnalysis,
      ``,
      `— Generated by SongAnalyzer`,
    ].join('\n');
}
